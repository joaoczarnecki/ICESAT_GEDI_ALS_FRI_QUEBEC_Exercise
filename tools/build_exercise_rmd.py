"""
build_exercise_rmd.py - write exercise.Rmd from exercise_template.Rmd, pasting the complete code of each script
into the chunks that ask for it with a line  #@include scripts/<file>

Author:    João Paulo Czarnecki de Liz (developer)
Co-author: Claude (Anthropic), AI coding assistant
Licence:   MIT (see LICENSE)

The scripts in scripts/ stay the single source of the code; rerun this after changing one of them.
Two edits are made while pasting, because the R Markdown file defines the helpers once, at the top:
  * a line that source()s summarise_lidar_by_polygon.R or check_data.R becomes a comment;
  * the "run from the command line" block at the end of check_data.R is dropped.

Run   python tools/build_exercise_rmd.py          (from the repository root)
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TEMPLATE = os.path.join(ROOT, "exercise_template.Rmd")
OUT = os.path.join(ROOT, "exercise.Rmd")
NOTICE = ("<!-- This file is generated by tools/build_exercise_rmd.py from exercise_template.Rmd and the scripts in\n"
          "     scripts/. To change the code, edit the script (or the template) and rebuild. -->")
SOURCE_LINE = re.compile(r'^\s*source\(.*(summarise_lidar_by_polygon|check_data)\.R.*\)\s*(#.*)?$')


def script_code(rel):
    with open(os.path.join(ROOT, rel), encoding="utf-8") as fh:
        lines = fh.read().rstrip("\n").split("\n")
    out = []
    for line in lines:
        if rel.endswith(".R") and SOURCE_LINE.match(line):
            out.append("# (the helpers of that file are defined in the 'Helpers' chunks at the top)")
            continue
        if rel.endswith("check_data.R") and line.startswith("if (sys.nframe() == 0)"):
            break                                   # command-line block: not needed inside R Markdown
        if line.startswith("```"):
            sys.exit(f"{rel}: a line starts with ``` and would end the chunk")
        out.append(line)
    while out and not out[-1].strip():
        out.pop()
    return out


def main():
    with open(TEMPLATE, encoding="utf-8") as fh:
        lines = fh.read().split("\n")
    out, n = [], 0
    for line in lines:
        m = re.match(r"^#@include\s+(\S+)\s*$", line)
        if m:
            out.extend(script_code(m.group(1)))
            n += 1
        elif line.strip() == "<!-- GENERATED-NOTICE -->":
            out.append(NOTICE)
        else:
            out.append(line)
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out))
    print(f"wrote {OUT}: {n} scripts pasted, {len(out)} lines")


if __name__ == "__main__":
    main()
